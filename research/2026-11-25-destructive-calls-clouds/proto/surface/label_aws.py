def label(op):
    name, sv = op["name"], op["service"]
    o = OVERRIDE.get(sv, {}).get(name)
    if o:
        return o
    if TAGS.match(name) or name.endswith("Tagging"):
        return "allow", "tags"
    for rx, lab, why in DEFAULT:
        if re.match(rx, name):
            return lab, why
    return "allow", ""


def main():
    ops = json.load(open(os.path.join(HERE, "ops", "aws.json")))
    known = {(o["service"], o["name"]) for o in ops}
    for sv, d in OVERRIDE.items():
        for n in d:
            assert (sv, n) in known, (sv, n)
    with open(os.path.join(HERE, "labels", "aws.txt"), "w") as f:
        f.write("# AWS (20 services), from botocore 1.43.62's models, labelled by hand on 2026-11-25.\n"
                "# Key: service Operation. A default by first word (label_aws.py), every operation read and corrected.\n")
        for op in ops:
            lab, why = label(op)
            f.write("%s %s %s %s\n" % (op["service"], op["name"], lab, why))
    print("aws", len(ops))


if __name__ == "__main__":
    main()
